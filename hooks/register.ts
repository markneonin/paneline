import type { Register } from "claude-code";

import { trackActivity } from "./activity-track";
import { trackAgents, trackAgentsClose } from "./agents-track";
import { renderChat } from "./chat-render";
import { holdRiskyCommands } from "./guard-hold";
import { trackGit } from "./git-track";
import { trackHistory } from "./history-track";
import { trackMcpUses } from "./mcp-track";
import { registerProbe } from "./probe";
import { trackProgress } from "./progress-track";
import { trackPromptInfo } from "./prompt-track";
import { trackRemote } from "./remote-track";
import { registerSessionCommand, registerSessionPane } from "./session-pane";
import { trackReviewComments } from "./review-track";
import { trackSessions } from "./sessions-track";
import { trackShells } from "./shells-track";
import { trackStore } from "./store-queue";
import { trackSkills } from "./skills-track";
import { trackSpend } from "./spend-track";
import { registerTabs } from "./tabs";
import { trackTheme } from "./theme-track";
import { trackUsage } from "./usage-track";

export const register: Register = (on, options) => {
  if (options.probe === true) registerProbe(on);
  trackStore(on);
  registerSessionPane(on);
  trackAgents(on);
  trackGit(on);
  trackShells(on);
  trackRemote(on);
  trackPromptInfo(on);
  trackActivity(on);
  if (options.guard === true) holdRiskyCommands(on);
  trackProgress(on);
  trackReviewComments(on);
  trackUsage(on);
  trackTheme(on);
  trackSkills(on);
  trackMcpUses(on);
  trackSpend(on);
  trackHistory(on);
  trackSessions(on);
  registerTabs(on);
  trackAgentsClose(on);
  registerSessionCommand(on, options.autoOpen !== false);
  renderChat(on);
};
